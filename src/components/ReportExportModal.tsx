import React, { useState } from 'react';
import { CompatibilityAnalysisResult } from '../types/analyzer';
import { Download, Copy, Check, Printer, FileText } from 'lucide-react';

interface ReportExportModalProps {
  isOpen: boolean;
  onClose: () => void;
  result: CompatibilityAnalysisResult;
  roleTitle?: string;
}

export const ReportExportModal: React.FC<ReportExportModalProps> = ({
  isOpen,
  onClose,
  result,
  roleTitle,
}) => {
  const [copied, setCopied] = useState<boolean>(false);

  if (!isOpen) return null;

  const generateMarkdownReport = (): string => {
    return `# TalentSync Compatibility & Career Intelligence Report
**Target Role:** ${roleTitle || 'Target Opportunity'}
**Overall Match Score:** ${result.overallScore}% (${result.matchTier})
**Headline Verdict:** ${result.headlineVerdict}

---

## 1. Score Breakdown
- Hard Skills & Tech Stack: ${result.scoreBreakdown.hardSkillsMatch}%
- Experience Relevance: ${result.scoreBreakdown.experienceRelevance}%
- ATS Readability & Keywords: ${result.scoreBreakdown.atsReadabilityAndKeywords}%
- Impact & Quantification: ${result.scoreBreakdown.impactAndQuantification}%
- Seniority & Scope Match: ${result.scoreBreakdown.seniorityAndScopeMatch}%

---

## 2. Executive Summary
${result.executiveSummary}

---

## 3. Competitive Advantages & Strengths
${result.keyStrengths
  .map(
    (s, idx) =>
      `### ${idx + 1}. ${s.title}\n- **Evidence:** ${s.description}\n- **JD Alignment:** ${s.jdAlignment}`
  )
  .join('\n\n')}

---

## 4. Vulnerabilities & Gaps to Address
${result.vulnerabilitiesAndGaps
  .map(
    (v, idx) =>
      `### ${idx + 1}. ${v.title} [${v.severity} Severity]\n- **Gap:** ${v.description}\n- **Mitigation Strategy:** ${v.howToMitigate}`
  )
  .join('\n\n')}

---

## 5. Targeted Skills to Learn Roadmap
${result.skillsToLearn
  .map(
    (sk, idx) =>
      `### ${idx + 1}. ${sk.skill} (${sk.category} - ${sk.priority} Priority)\n- **Why It Matters:** ${sk.whyItMatters}\n- **Timeframe:** ${sk.timeToLearn}\n- **Recommended Proof Project:** ${sk.recommendedProjectOrResource}`
  )
  .join('\n\n')}

---

## 6. High-Value Missing Keywords
${result.keywordOptimization.missingKeywords
  .map((k) => `- **${k.keyword}** (${k.importance} Priority, ${k.frequencyInJd}x in JD) -> Placement: ${k.suggestedPlacement}`)
  .join('\n')}

---

## 7. Role-Specific Interview Questions
${result.interviewQuestions
  .map(
    (q, idx) =>
      `### Question ${idx + 1} (${q.category})\n> "${q.question}"\n\n- **Interviewer Intent:** ${q.interviewerIntent}\n- **Strategy:** ${q.suggestedStrategy}\n- **Key Signals:** ${q.keySignalsToConvey.join(', ')}`
  )
  .join('\n\n')}

---

## 8. 24-Hour Quick Optimization Checklist
${result.quickWinsChecklist.map((step, idx) => `${idx + 1}. ${step}`).join('\n')}

*Generated by TalentSync AI Career Intelligence*
`;
  };

  const markdown = generateMarkdownReport();

  const handleCopyMarkdown = () => {
    navigator.clipboard.writeText(markdown);
    setCopied(true);
    setTimeout(() => setCopied(false), 2000);
  };

  const handleDownloadFile = () => {
    const blob = new Blob([markdown], { type: 'text/markdown;charset=utf-8' });
    const url = URL.createObjectURL(blob);
    const a = document.createElement('a');
    a.href = url;
    a.download = `TalentSync-Report-${(roleTitle || 'Analysis').replace(/\s+/g, '-')}.md`;
    a.click();
    URL.revokeObjectURL(url);
  };

  const handlePrint = () => {
    window.print();
  };

  return (
    <div className="fixed inset-0 z-50 flex items-center justify-center p-4 bg-slate-900/40 backdrop-blur-xs">
      <div className="relative w-full max-w-3xl max-h-[85vh] flex flex-col rounded-2xl border border-slate-200 bg-white shadow-2xl">
        {/* Header */}
        <div className="flex items-center justify-between p-5 border-b border-slate-100">
          <div className="flex items-center gap-2">
            <div className="flex h-7 w-7 items-center justify-center rounded-lg bg-indigo-50 text-indigo-600 border border-indigo-200">
              <FileText className="h-4 w-4" />
            </div>
            <h3 className="text-sm font-bold text-slate-900">
              Export Comprehensive Career Intelligence Report
            </h3>
          </div>
          <button
            onClick={onClose}
            className="text-slate-400 hover:text-slate-700 p-1 text-sm font-bold"
          >
            ✕
          </button>
        </div>

        {/* Content Preview */}
        <div className="flex-1 p-5 overflow-y-auto bg-slate-50">
          <pre className="rounded-xl border border-slate-200 bg-white p-4 font-mono text-[11px] text-slate-800 whitespace-pre-wrap leading-relaxed shadow-xs">
            {markdown}
          </pre>
        </div>

        {/* Footer Actions */}
        <div className="flex items-center justify-between p-4 border-t border-slate-100 bg-white">
          <div className="text-xs text-slate-500 font-medium">
            Formatted as clean Markdown documentation
          </div>

          <div className="flex items-center gap-2">
            <button
              onClick={handlePrint}
              className="flex items-center gap-1.5 rounded-xl border border-slate-200 bg-white px-3 py-1.5 text-xs font-semibold text-slate-700 hover:bg-slate-50 transition-colors shadow-xs"
            >
              <Printer className="h-3.5 w-3.5 text-slate-600" />
              <span>Print / PDF</span>
            </button>
            <button
              onClick={handleCopyMarkdown}
              className="flex items-center gap-1.5 rounded-xl border border-slate-200 bg-white px-3 py-1.5 text-xs font-semibold text-slate-700 hover:bg-slate-50 transition-colors shadow-xs"
            >
              {copied ? (
                <>
                  <Check className="h-3.5 w-3.5 text-emerald-600" />
                  <span className="text-emerald-700 font-bold">Copied</span>
                </>
              ) : (
                <>
                  <Copy className="h-3.5 w-3.5 text-slate-600" />
                  <span>Copy Markdown</span>
                </>
              )}
            </button>
            <button
              onClick={handleDownloadFile}
              className="flex items-center gap-1.5 rounded-xl bg-indigo-600 px-4 py-1.5 text-xs font-bold text-white hover:bg-indigo-700 transition-colors shadow-xs"
            >
              <Download className="h-3.5 w-3.5" />
              <span>Download .MD</span>
            </button>
          </div>
        </div>
      </div>
    </div>
  );
};
